  const sourceText = new WeakMap();
  const sourceAria = new WeakMap();
  let language = "en";

  function preferredLanguage() {
    try {
      const query = new URLSearchParams(window.location.search).get("lang");
      if (query === "en" || query === "ja") return query;
      const stored = localStorage.getItem("cfg-language");
      if (stored === "en" || stored === "ja") return stored;
    } catch (_) {}
    return document.documentElement.lang === "ja" ? "ja" : "en";
  }

  function translation(key, fallback) {
    if (language === "ja" && Object.prototype.hasOwnProperty.call(JA, key)) return JA[key];
    return fallback ?? key;
  }

  function rememberSources() {
    document.querySelectorAll("[data-i18n]").forEach((element) => {
      if (!sourceText.has(element)) sourceText.set(element, element.textContent);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
      if (!sourceAria.has(element)) sourceAria.set(element, element.getAttribute("aria-label") || "");
    });
  }

  function localizedLink(target) {
    try {
      const url = new URL(target, window.location.href);
      url.searchParams.set("lang", language);
      if (url.protocol === "file:" || url.origin === window.location.origin) {
        return `${url.pathname.split("/").pop() || "index.html"}${url.search}${url.hash}`;
      }
      return url.href;
    } catch (_) {
      const parts = String(target).split("#");
      const join = parts[0].includes("?") ? "&" : "?";
      return `${parts[0]}${join}lang=${language}${parts[1] ? `#${parts[1]}` : ""}`;
    }
  }

  function updateMeta() {
    const page = document.body?.dataset.page || "group";
    const meta = PAGE_META[page]?.[language];
    if (!meta) return;
    document.title = meta.title;
    document.querySelector('meta[name="description"]')?.setAttribute("content", meta.description);
    document.querySelector('meta[property="og:title"]')?.setAttribute("content", meta.ogTitle);
    document.querySelector('meta[property="og:description"]')?.setAttribute("content", meta.ogDescription);
  }

  function setLanguage(next, options = {}) {
    language = next === "ja" ? "ja" : "en";
    rememberSources();
    document.documentElement.lang = language;
    document.documentElement.dataset.lang = language;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.dataset.i18n;
      element.textContent = language === "ja" ? translation(key, sourceText.get(element)) : sourceText.get(element);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
      const key = element.dataset.i18nAria;
      element.setAttribute("aria-label", language === "ja" ? translation(key, sourceAria.get(element)) : sourceAria.get(element));
    });

    const button = document.querySelector("#lang-button");
    if (button) {
      button.textContent = language === "ja" ? "English" : "日本語";
      button.setAttribute("aria-label", language === "ja" ? "英語に切り替える" : "Switch to Japanese");
    }
    document.querySelectorAll("[data-lang-link]").forEach((link) => {
      if (!link.dataset.baseHref) link.dataset.baseHref = link.getAttribute("href") || "";
      link.setAttribute("href", localizedLink(link.dataset.baseHref));
    });
    updateMeta();
    try { localStorage.setItem("cfg-language", language); } catch (_) {}
    document.documentElement.classList.remove("i18n-pending");
    if (!options.silent) {
      const detail = { language };
      document.dispatchEvent(new CustomEvent("cfg:languagechange", { detail }));
      window.dispatchEvent(new CustomEvent("cfg:languagechange", { detail }));
    }
  }

  window.CFG_I18N = {
    t(key) {
      return translation(key, key);
    },
    current() { return language; },
    setLanguage,
    withLanguage: localizedLink,
    link: localizedLink
  };

